type golden struct {
	Name         string
	Request      port.HelperCorrelation
	Phase        string
	Error        *string
	Handoff      string
	HandoffBytes int
	Accepted     bool
	Continue     string
}

func TestSidecarPresentationSurvivesHandoffAndContinueCodec(t *testing.T) {
	mode := "sidecar-only"
	c := port.HelperCorrelation{OperationID: "fixture", RelaunchPresentation: &mode}
	codec := helperprotocol.JSONCodec{}
	b, err := codec.Handoff(port.HelperHandoffFrame{Schema: "fixture", Phase: "waiting_for_exit", Correlation: c})
	if err != nil || !bytes.Contains(b, []byte(`"relaunchPresentation":"sidecar-only"`)) {
		t.Fatal("missing presentation in ACK", err)
	}
	var wire map[string]any
	if json.Unmarshal(b, &wire) != nil {
		t.Fatal("invalid frame")
	}
	delete(wire, "phase")
	b, err = json.Marshal(wire)
	if err != nil {
		t.Fatal(err)
	}
	f, err := codec.Continue(b)
	if err != nil || f.Correlation.RelaunchPresentation == nil || *f.Correlation.RelaunchPresentation != mode {
		t.Fatal("presentation lost in continuation", err)
	}
	for _, bad := range []any{nil, true, []string{"sidecar-only"}} {
		wire["relaunchPresentation"] = bad
		b, _ = json.Marshal(wire)
		if _, err := codec.Continue(b); err == nil {
			t.Fatal("invalid presentation structure accepted")
		}
	}
}

func goldens(t *testing.T) []golden {
	t.Helper()
	b, err := os.ReadFile("testdata/golden.json")
	if err != nil {
		t.Fatal(err)
	}
	var vectors []golden
	if err := json.Unmarshal(b, &vectors); err != nil {
		t.Fatal(err)
	}
	if len(vectors) != 9 {
		t.Fatal("missing independent vectors")
	}
	return vectors
}

func TestIndependentProducerAndObserverVectors(t *testing.T) {
	codec := helperprotocol.JSONCodec{}
	for _, v := range goldens(t) {
		t.Run(v.Name, func(t *testing.T) {
			frame := port.HelperHandoffFrame{Schema: "farol.installed-update-handoff/1", Phase: v.Phase, Correlation: v.Request, Error: v.Error}
			got, err := codec.Handoff(frame)
			if len(v.Handoff) != v.HandoffBytes {
				t.Fatal("invalid golden size")
			}
			if !v.Accepted {
				if err == nil || err.Error() != "helper_protocol_size" || got != nil {
					t.Fatalf("oversized handoff = %d bytes, %v", len(got), err)
				}
			} else {
				if err != nil || string(got) != v.Handoff {
					t.Fatalf("Python byte mismatch: %q, %v; want %q", got, err, v.Handoff)
				}
				for _, b := range got {
					if b >= 127 {
						t.Fatal("non-ASCII output")
					}
				}
				var observed map[string]any
				if json.Unmarshal(got, &observed) != nil || observed["phase"] != v.Phase || len(observed) != 8+optionalCount(v) {
					t.Fatal("observer shape changed")
				}
			}
			continued, err := codec.Continue([]byte(v.Continue))
			if len(v.Continue) > 4096 {
				if err == nil || err.Error() != "helper_protocol_size" || !reflect.DeepEqual(continued, port.HelperContinueFrame{}) {
					t.Fatal("oversized continue accepted")
				}
			} else if err != nil || continued.Schema != "farol.installed-update-continue/1" || !reflect.DeepEqual(continued.Correlation, v.Request) {
				t.Fatalf("TS continue value mismatch: %#v, %v", continued, err)
			}
		})
	}
}

func optionalCount(v golden) int {
	n := 0
	if v.Request.Predecessor != nil {
		n++
	}
	if v.Request.LeaseIdentity != nil {
		n++
	}
	if v.Error != nil {
		n++
	}
	return n
}

// Deliberately independent bytes: malformed frames are not generated by the codec.
const simple = `{"schema":"arbitrary","operationId":"operation","action":"arbitrary","source":{"digest":"s","version":"1","buildId":"s1"},"target":{"digest":"t","version":"2","buildId":"t2"},"pid":123,"processStart":"start"}`
const predecessor = `{"kind":"arbitrary","startedAt":"when","lastQuitSha256":"hash","stateIdentity":{"device":"d","inode":"i"}}`
const lease = `{"device":"ld","inode":"li"}`

func withOptional(key, value string) string {
	return strings.TrimSuffix(simple, "}") + `,"` + key + `":` + value + `}`
}

func TestContinueRejectsIndependentMalformedFrames(t *testing.T) {
	cases := map[string]string{
		"empty": "", "array": `[]`, "root-null": `null`, "scalar": `"frame"`,
		"truncated": strings.TrimSuffix(simple, "}"), "trailing-object": simple + `{}`,
		"trailing-garbage": simple + "x", "trailing-comma": strings.TrimSuffix(simple, "}") + ",}",
		"unknown": withOptional("unexpected", `"secret"`),
		"phase":   withOptional("phase", `"waiting_for_exit"`), "error": withOptional("error", `"refused"`),
		"duplicate": withOptional("schema", `"other"`), "escaped-duplicate": withOptional(`\u0073chema`, `"other"`),
		"null-predecessor": withOptional("predecessor", "null"), "null-lease": withOptional("leaseIdentity", "null"),
		"array-predecessor": withOptional("predecessor", "[]"), "string-lease": withOptional("leaseIdentity", `"x"`),
		"high-surrogate": strings.Replace(simple, `"operation"`, `"\ud800"`, 1),
		"low-surrogate":  strings.Replace(simple, `"operation"`, `"\udfff"`, 1),
		"reversed-pair":  strings.Replace(simple, `"operation"`, `"\udc00\ud800"`, 1),
		"bad-pair":       strings.Replace(simple, `"operation"`, `"\ud800\u0041"`, 1),
		"surrogate-key":  withOptional(`\ud800`, `"x"`),
		"bad-hex":        strings.Replace(simple, `"operation"`, `"\u00xz"`, 1),
		"bad-escape":     strings.Replace(simple, `"operation"`, `"\x41"`, 1),
		"raw-control":    strings.Replace(simple, "operation", "\x01", 1),
		"invalid-utf8":   strings.Replace(simple, "operation", string([]byte{0xff}), 1),
		"utf8-surrogate": strings.Replace(simple, "operation", string([]byte{0xed, 0xa0, 0x80}), 1),
	}
	for _, pid := range []string{`"123"`, "null", "true", "[]", "{}", "1.0", "1e2", "1E0", "+1", "01", "9223372036854775808", "-9223372036854775809"} {
		cases["pid-"+pid] = strings.Replace(simple, `"pid":123`, `"pid":`+pid, 1)
	}
	for _, field := range []string{`"schema":"arbitrary",`, `"operationId":"operation",`, `"action":"arbitrary",`, `"source":{"digest":"s","version":"1","buildId":"s1"},`, `"target":{"digest":"t","version":"2","buildId":"t2"},`, `"pid":123,`, `,"processStart":"start"`} {
		cases["missing-"+field] = strings.Replace(simple, field, "", 1)
	}
	for _, text := range []string{`"arbitrary"`, `"operation"`, `"s"`, `"1"`, `"s1"`, `"t"`, `"2"`, `"t2"`, `"start"`} {
		for _, bad := range []string{"null", "123", "false", "[]", "{}"} {
			cases["type-"+text+bad] = strings.Replace(simple, text, bad, 1)
		}
	}
	for _, key := range []string{"source", "target"} {
		old := `{"digest":"s","version":"1","buildId":"s1"}`
		if key == "target" {
			old = `{"digest":"t","version":"2","buildId":"t2"}`
		}
		for name, bad := range map[string]string{
			"null": `null`, "array": `[]`, "missing": `{"digest":"d","version":"v"}`,
			"extra":     `{"digest":"d","version":"v","buildId":"b","x":"x"}`,
			"duplicate": `{"digest":"d","version":"v","buildId":"b","\u0064igest":"other"}`,
		} {
			cases[key+"-"+name] = strings.Replace(simple, old, bad, 1)
		}
	}
	for name, bad := range map[string]string{
		"missing":             `{"kind":"k","startedAt":"s","lastQuitSha256":"h"}`,
		"extra":               strings.TrimSuffix(predecessor, "}") + `,"extra":"x"}`,
		"duplicate":           strings.TrimSuffix(predecessor, "}") + `,"\u006bind":"x"}`,
		"null-text":           strings.Replace(predecessor, `"when"`, "null", 1),
		"null-state":          strings.Replace(predecessor, `{"device":"d","inode":"i"}`, "null", 1),
		"missing-state-key":   strings.Replace(predecessor, `,"inode":"i"`, "", 1),
		"duplicate-state-key": strings.Replace(predecessor, `"inode":"i"`, `"inode":"i","\u0069node":"other"`, 1),
		"extra-state-key":     strings.Replace(predecessor, `"inode":"i"`, `"inode":"i","extra":"x"`, 1),
	} {
		cases["predecessor-"+name] = withOptional("predecessor", bad)
	}
	for name, bad := range map[string]string{
		"missing": `{"device":"d"}`, "extra": `{"device":"d","inode":"i","x":"x"}`,
		"duplicate":  `{"device":"d","inode":"i","\u0064evice":"other"}`,
		"wrong-type": `{"device":"d","inode":123}`, "null-field": `{"device":null,"inode":"i"}`,
		"surrogate": `{"device":"\ud800","inode":"i"}`,
	} {
		cases["lease-"+name] = withOptional("leaseIdentity", bad)
	}
	for name, input := range cases {
		t.Run(name, func(t *testing.T) {
			got, err := (helperprotocol.JSONCodec{}).Continue([]byte(input))
			if err == nil || err.Error() != "helper_protocol_input" || !reflect.DeepEqual(got, port.HelperContinueFrame{}) {
				t.Fatalf("malformed frame returned %#v, %v", got, err)
			}
		})
	}
}

func TestContinueStructuralBoundaryAndOwnership(t *testing.T) {
	codec := helperprotocol.JSONCodec{}
	for name, input := range map[string]string{
		"policy-is-not-codec": simple,
		"predecessor-alone":   withOptional("predecessor", predecessor),
		"lease-alone":         withOptional("leaseIdentity", lease),
		"escaped-key":         strings.Replace(simple, `"schema"`, `"\u0073chema"`, 1),
		"paired-unicode":      strings.Replace(simple, `"operation"`, `"\ud83d\ude42\u007f\u2028"`, 1),
		"escaped-backslash":   strings.Replace(simple, `"operation"`, `"\\ud800\"end"`, 1),
		"raw-unicode":         strings.Replace(simple, `"operation"`, `"é🙂"`, 1),
		"min-pid":             strings.Replace(simple, `"pid":123`, `"pid":-9223372036854775808`, 1),
		"max-pid":             strings.Replace(simple, `"pid":123`, `"pid":9223372036854775807`, 1),
		"negative-zero":       strings.Replace(simple, `"pid":123`, `"pid":-0`, 1),
		"whitespace":          " \n\t" + simple + "\r\n",
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := codec.Continue([]byte(input)); err != nil {
				t.Fatal(err)
			}
		})
	}
	for _, size := range []int{4095, 4096, 4097} {
		input := append([]byte(simple), bytes.Repeat([]byte(" "), size-len(simple))...)
		_, err := codec.Continue(input)
		if (err == nil) != (size <= 4096) {
			t.Fatalf("continue size %d: %v", size, err)
		}
		if size > 4096 && err.Error() != "helper_protocol_size" {
			t.Fatal("incorrect size classification", err)
		}
	}
	input := []byte(withOptional("predecessor", predecessor))
	got, err := codec.Continue(input)
	if err != nil {
		t.Fatal(err)
	}
	for i := range input {
		input[i] = 'x'
	}
	if got.Correlation.OperationID != "operation" || got.Correlation.Predecessor.StateIdentity.Device != "d" {
		t.Fatal("returned input aliases")
	}
	second, err := codec.Continue([]byte(withOptional("predecessor", predecessor)))
	if err != nil {
		t.Fatal(err)
	}
	got.Correlation.Predecessor.Kind = "mutated"
	if second.Correlation.Predecessor.Kind != "arbitrary" {
		t.Fatal("shared output state")
	}
}

func TestHandoffRejectsMalformedStringsInEveryPosition(t *testing.T) {
	names := []string{"schema", "phase", "operation", "action", "source-digest", "source-version", "source-build", "target-digest", "target-version", "target-build", "process-start", "predecessor-kind", "predecessor-start", "predecessor-quit", "state-device", "state-inode", "lease-device", "lease-inode", "error"}
	for i, name := range names {
		t.Run(name, func(t *testing.T) {
			errText := ""
			f := port.HelperHandoffFrame{Correlation: port.HelperCorrelation{Predecessor: &port.HelperPredecessor{}, LeaseIdentity: &port.HelperIdentity{}}, Error: &errText}
			c := &f.Correlation
			p := c.Predecessor
			fields := []*string{&f.Schema, &f.Phase, &c.OperationID, &c.Action, &c.Source.Digest, &c.Source.Version, &c.Source.BuildID, &c.Target.Digest, &c.Target.Version, &c.Target.BuildID, &c.ProcessStart, &p.Kind, &p.StartedAt, &p.LastQuitSHA256, &p.StateIdentity.Device, &p.StateIdentity.Inode, &c.LeaseIdentity.Device, &c.LeaseIdentity.Inode, f.Error}
			for _, invalid := range []string{string([]byte{0xff}), strings.Repeat("x", 4097)} {
				*fields[i] = invalid
				got, err := (helperprotocol.JSONCodec{}).Handoff(f)
				want := "helper_protocol_encoding"
				if len(invalid) > 4096 {
					want = "helper_protocol_size"
				}
				if got != nil || err == nil || err.Error() != want {
					t.Fatalf("invalid string returned %d bytes, %v", len(got), err)
				}
			}
		})
	}
}

func TestHandoffDoesNotApplyPolicyOrRetainAliases(t *testing.T) {
	empty := ""
	f := port.HelperHandoffFrame{Schema: "unknown", Phase: "unknown", Correlation: port.HelperCorrelation{PID: -1, LeaseIdentity: &port.HelperIdentity{Device: "d"}}, Error: &empty}
	codec := helperprotocol.JSONCodec{}
	got, err := codec.Handoff(f)
	if err != nil {
		t.Fatal(err)
	}
	want := `{"schema":"unknown","phase":"unknown","operationId":"","action":"","source":{"digest":"","version":"","buildId":""},"target":{"digest":"","version":"","buildId":""},"pid":-1,"processStart":"","leaseIdentity":{"device":"d","inode":""},"error":""}` + "\n"
	if string(got) != want || f.Correlation.LeaseIdentity.Device != "d" || *f.Error != "" {
		t.Fatal("structural mapping or input mutation")
	}
	got[0] = 'x'
	again, err := codec.Handoff(f)
	if err != nil || string(again) != want {
		t.Fatal("shared output buffer")
	}
}
