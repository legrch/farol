// False is only predicate parity, never a positive compatibility claim.
func TestPredecessorStateOriginalPythonOracle(t *testing.T) {
	versions := []string{
		"",
		"0.1.",
		"0.1.0",
		"0.1.99",
		"0.1",
		"0.10.0",
		"0.2.0",
		"0.3.0",
		"0.2.0-owner.beta.0",
		"0.2.0-owner.beta.1",
		"0.2.0-owner.beta.2",
		"0.2.0-owner.beta.3",
		"0.2.0-owner.beta.4",
		"0.2.0-owner.beta.5",
		"0.2.0-owner.beta.6",
		"0.2.0-owner.beta.7",
		"0.2.0-owner.beta.8",
		"0.2.0-owner.beta.9",
		"0.2.0-owner.beta.10",
		"0.2.0-owner.beta.11",
		"0.2.0-owner.beta.12",
		"0.2.0-owner.beta.13",
		"0.2.0-owner.beta.01",
		"0.2.0-owner.beta.09",
		"0.2.0-owner.beta.010",
		"0.2.0-owner.beta.11\n",
		"0.2.0-owner.beta.9\n",
		"0.2.0-owner.beta.9x",
		" 0.1.0",
		"0.1.0\n",
		"0.2.0-owner.beta.٣",
		"0.2.0-owner.beta.1.0",
	}
	want := []string{
		"00000000000000000000000000000000",
		"10001111111111111111111111111011",
		"10001111111111111111111111111011",
		"10001111111111111111111111111011",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
		"11111111100000000011111111111111",
		"11111111100000000011111111111111",
		"11111111111111111111111111111111",
		"11111111100000000011111111111111",
		"11111111100000000011111111111111",
		"11111111100000000011111111111111",
		"11111111100000000011111111111111",
		"11111111100000000011111111111111",
		"11111111100000000011111111111111",
		"11111111100000000000111111111111",
		"11111111100000000000111111111111",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
		"10001111111111111111111111111011",
		"00000000000000000000000000000000",
		"00000000000000000000000000000000",
	}
	for i, source := range versions {
		for j, target := range versions {
			if got := PredecessorStateUnqualified(source, target); got != (want[i][j] == '1') {
				t.Fatalf("source=%q target=%q got=%t want=%c", source, target, got, want[i][j])
			}
		}
	}
}
