import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const bytes = fs.readFileSync(path.join(root, "api/desktop/v1/schema.json"));
const schema = JSON.parse(bytes.toString("utf8"));
if (schema.generator !== "farol-wire/1") throw Error("unsupported generator");
const digest = crypto.createHash("sha256").update(bytes).digest("hex");
const title = `Generated by farol-wire/1; schema SHA-256 ${digest}. DO NOT EDIT.`;
const goTypes = {
  id: "string",
  nullableId: "*string",
  text: "string",
  decimal: "string",
  utc: "string",
  uint32: "uint32",
  int32: "int32",
  json: "json.RawMessage",
  "text[]": "[]string",
};
const tsTypes = {
  id: "string",
  nullableId: "string | null",
  text: "string",
  decimal: "string",
  utc: "string",
  uint32: "number",
  int32: "number",
  json: "Json",
  "text[]": "readonly string[]",
};
let go = `// ${title}\npackage desktop\nimport ("encoding/json"; "errors"; "math"; "regexp"; "strconv"; "strings"; "time")\n`;
go += `const ProtocolMajor uint32 = ${schema.protocolMajor}\nconst ProtocolMinor uint32 = ${schema.protocolMinor}\nconst SchemaSHA256 = "${digest}"\nconst Schema = ${JSON.stringify(bytes.toString("utf8"))}\n`;
go += `var MethodNames = []string{${Object.keys(schema.methods).sort().map(JSON.stringify).join(",")}}\nvar Methods = map[string]string{${Object.entries(
  schema.methods,
)
  .map(([k, v]) => `${JSON.stringify(k)}:${JSON.stringify(v)}`)
  .join(",")}}\n`;
let ts = `// ${title}\nexport const protocolMajor = ${schema.protocolMajor};\nexport const protocolMinor = ${schema.protocolMinor};\nexport const maxFrameBytes = ${schema.maxFrameBytes};\nexport const schemaSHA256 = "${digest}";\nexport type Json = null | boolean | number | string | readonly Json[] | { readonly [key: string]: Json };\n`;
for (const [name, def] of Object.entries(schema.definitions)) {
  go += `type ${name} struct {\n`;
  ts += `export interface ${name} {\n`;
  for (const [field, spec] of Object.entries(def.fields)) {
    const goType = goTypes[spec.type] ?? spec.type;
    go += `${field[0].toUpperCase() + field.slice(1)} ${spec.optional && spec.type !== "json" ? "*" : ""}${goType} \`json:"${field}${spec.optional ? ",omitempty" : ""}"\`\n`;
    const tsType = spec.values
      ? spec.values.map(JSON.stringify).join(" | ")
      : (tsTypes[spec.type] ?? spec.type);
    ts += `readonly ${field}${spec.optional ? "?" : ""}: ${tsType};\n`;
  }
  go += "}\n";
  ts += "}\n";
  const numeric = Object.entries(def.fields)
    .filter(([, spec]) => ["uint32", "int32"].includes(spec.type))
    .map(([field]) => field);
  if (numeric.length) {
    go += `func (value *${name}) UnmarshalJSON(raw []byte) error { type plain ${name}; var decoded plain; if err := decodeIntegers("${name}",raw,&decoded,[]string{${numeric.map(JSON.stringify).join(",")}}); err != nil { return err }; *value = ${name}(decoded); return nil }\n`;
  }
}
go += fs.readFileSync(
  path.join(root, "tooling/desktop-validator.go.txt"),
  "utf8",
);
ts += `const schema = ${JSON.stringify(schema)} as const;\n`;
ts += fs.readFileSync(
  path.join(root, "tooling/desktop-validator.ts.txt"),
  "utf8",
);
const formattedGo = execFileSync("gofmt", { input: go, encoding: "utf8" });
const outputs = {
  "gen/desktop/v1/wire.go": formattedGo,
  "apps/desktop/bridge/wire.ts": ts,
};
// Prettier is the existing TS authority. Its exact locked formatter is used here.
for (const [file, source] of Object.entries(outputs)) {
  const content = file.endsWith(".ts")
    ? execFileSync(
        process.execPath,
        [
          path.join(root, "node_modules/prettier/bin/prettier.cjs"),
          "--stdin-filepath",
          file,
        ],
        { input: source, encoding: "utf8" },
      )
    : source;
  const target = path.join(root, file);
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== content)
      throw Error(`generated wire drift: ${file}`);
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
}
process.stdout.write(`desktop wire ${schema.generator} ${digest}\n`);
