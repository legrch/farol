import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const bytes = fs.readFileSync(path.join(root, "api/desktop/v1/schema.json"));
const schema = JSON.parse(bytes.toString("utf8"));
if (schema.generator !== "farol-wire/2") throw Error("unsupported generator");
if (
  !schema.methods ||
  Array.isArray(schema.methods) ||
  Object.keys(schema.methods).length === 0 ||
  Object.keys(schema.methods).length > 128 ||
  Object.entries(schema.methods).some(
    ([name, kind]) =>
      !/^[a-z]+(?:\.[a-z]+)+$/u.test(name) ||
      !["read", "effect"].includes(kind),
  )
)
  throw Error("invalid method classification");
// Protocol 1.0 has fixed mechanism limits in both peers. Refuse metadata drift
// until a coordinated implementation/version change supports different limits.
if (
  schema.maxFrameBytes !== 1048576 ||
  schema.maxDepth !== 32 ||
  schema.maxRequests !== 4096
)
  throw Error("unsupported wire limits");
const digest = crypto.createHash("sha256").update(bytes).digest("hex");
const title = `Generated by farol-wire/2; schema SHA-256 ${digest}. DO NOT EDIT.`;
const goTypes = {
  boolean: "bool",
  string: "string",
  id: "string",
  nullableId: "*string",
  text: "string",
  decimal: "string",
  utc: "string",
  uint32: "uint32",
  int32: "int32",
  json: "json.RawMessage",
  "text[]": "[]string",
  "method[]": "[]string",
};
const tsTypes = {
  boolean: "boolean",
  string: "string",
  id: "string",
  nullableId: "string | null",
  text: "string",
  decimal: "string",
  utc: "string",
  uint32: "number",
  int32: "number",
  json: "Json",
  "text[]": "readonly string[]",
  "method[]": "readonly string[]",
};
let go = `// ${title}\npackage desktop\nimport ("encoding/json"; "errors"; "math"; "regexp"; "strconv"; "strings"; "time"; "unicode/utf8")\n`;
go += `const ProtocolMajor uint32 = ${schema.protocolMajor}\nconst ProtocolMinor uint32 = ${schema.protocolMinor}\nconst SchemaSHA256 = "${digest}"\nconst Schema = ${JSON.stringify(bytes.toString("utf8"))}\n`;
const methodNames = Object.keys(schema.methods).sort();
const effectNames = methodNames.filter(
  (name) => schema.methods[name] === "effect",
);
go += `func MethodNames() []string { return []string{${methodNames.map(JSON.stringify).join(",")}} }\nfunc KnownMethod(name string) bool { switch name { case ${methodNames.map(JSON.stringify).join(",")}:return true };return false }\nfunc RequiresOperationID(name string) bool { ${effectNames.length ? `switch name { case ${effectNames.map(JSON.stringify).join(",")}:return true };` : ""}return false }\n`;
let ts = `// ${title}\nexport const protocolMajor = ${schema.protocolMajor};\nexport const protocolMinor = ${schema.protocolMinor};\nexport const maxFrameBytes = ${schema.maxFrameBytes};\nexport const schemaSHA256 = "${digest}";\nexport type Json = null | boolean | number | string | readonly Json[] | { readonly [key: string]: Json };\n`;
ts += `export const methodKinds = Object.freeze(${JSON.stringify(Object.fromEntries(methodNames.map((name) => [name, schema.methods[name]])))} as const);\nexport function knownMethod(name: string): boolean { return Object.hasOwn(methodKinds,name); }\nexport function requiresOperationID(name: string): boolean { return knownMethod(name) && methodKinds[name as keyof typeof methodKinds] === "effect"; }\n`;
for (const [name, def] of Object.entries(schema.definitions)) {
  go += `type ${name} struct {\n`;
  ts += `export interface ${name} {\n`;
  for (const [field, spec] of Object.entries(def.fields)) {
    if (spec.minItems !== undefined || spec.maxItems !== undefined) {
      const min = spec.minItems ?? 0;
      const max = spec.maxItems ?? (spec.type === "text[]" ? 64 : 128);
      if (
        !spec.type.endsWith("[]") ||
        !Number.isSafeInteger(min) ||
        !Number.isSafeInteger(max) ||
        min < 0 ||
        max < min ||
        max > 4096
      )
        throw Error(`invalid array limits: ${name}.${field}`);
    }
    const goType =
      goTypes[spec.type] ??
      (spec.type.endsWith("[]") ? `[]${spec.type.slice(0, -2)}` : spec.type);
    go += `${field[0].toUpperCase() + field.slice(1)} ${spec.optional && spec.type !== "json" ? "*" : ""}${goType} \`json:"${field}${spec.optional ? ",omitempty" : ""}"\`\n`;
    const tsType = spec.values
      ? spec.values.map(JSON.stringify).join(" | ")
      : (tsTypes[spec.type] ??
        (spec.type.endsWith("[]") ? `readonly ${spec.type}` : spec.type));
    ts += `readonly ${field}${spec.optional ? "?" : ""}: ${tsType};\n`;
  }
  go += "}\n";
  ts += "}\n";
  const numeric = Object.entries(def.fields)
    .filter(([, spec]) => ["uint32", "int32"].includes(spec.type))
    .map(([field]) => field);
  if (numeric.length) {
    go += `func (value *${name}) UnmarshalJSON(raw []byte) error { type plain ${name}; var decoded plain; if err := decodeIntegers("${name}",raw,&decoded,[]string{${numeric.map(JSON.stringify).join(",")}}); err != nil { return err }; *value = ${name}(decoded); return nil }\n`;
  }
}
go += fs.readFileSync(
  path.join(root, "tooling/desktop-validator.go.txt"),
  "utf8",
);
ts += `const schema = ${JSON.stringify(schema)} as const;\n`;
ts += fs.readFileSync(
  path.join(root, "tooling/desktop-validator.ts.txt"),
  "utf8",
);
const formattedGo = execFileSync("gofmt", { input: go, encoding: "utf8" });
const outputs = {
  "gen/desktop/v1/wire.go": formattedGo,
  "apps/desktop/bridge/wire.ts": ts,
};
// Prettier is the existing TS authority. Its exact locked formatter is used here.
for (const [file, source] of Object.entries(outputs)) {
  const content = file.endsWith(".ts")
    ? execFileSync(
        process.execPath,
        [
          path.join(root, "node_modules/prettier/bin/prettier.cjs"),
          "--stdin-filepath",
          file,
        ],
        { input: source, encoding: "utf8" },
      )
    : source;
  const target = path.join(root, file);
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== content)
      throw Error(`generated wire drift: ${file}`);
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
}
process.stdout.write(`desktop wire ${schema.generator} ${digest}\n`);
